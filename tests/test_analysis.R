suppressPackageStartupMessages(library(vegan))
source('scripts/lib.R')
n <- 0L
check <- function(x) { stopifnot(isTRUE(x)); n <<- n+1L }
counts <- rbind(deep=c(100,0,100), shallow=c(2,0,0), blank=c(0,100,0), empty=c(0,0,0))
colnames(counts) <- c('ASV1','ASV2','ASV3')
types <- c('sample','sample','negative','negative')
d <- assess_depth(counts,types,10)
check(identical(d$eligible,c(TRUE,FALSE,FALSE,FALSE)))
check(grepl('TOO SHALLOW',d$status[2]))
check(all(grepl('CONTROL',d$status[3:4])))
check(inherits(try(assess_depth(counts,types,0),silent=TRUE),'try-error'))
s <- control_screen(counts,types)
check(identical(s$table$flag,c(FALSE,TRUE,FALSE)))
check(s$table$blank_prevalence[2]==1)
check(grepl('no negative',control_screen(counts[1:2,],types[1:2])$status))
check(grepl('no retained',control_screen(counts[c(1,4),],types[c(1,4)])$status))
check(!any(control_screen(counts[1:2,],types[1:2])$table$flag))
x <- matrix(c(2,2),nrow=1,dimnames=list('known',c('a','b')))
check(abs(as.numeric(rarefy(x,2))-5/3)<1e-10)
r <- rarefaction_table(counts)
check(all(r$expected_asvs[r$sample=='empty']==0))
check(all(diff(r$expected_asvs[r$sample=='deep'])>=-1e-10))
check(abs(diversity(x)-log(2))<1e-10)
b <- as.matrix(vegdist(rbind(c(4,0),c(0,4),c(4,0)),method='bray'))
check(b[1,2]==1 && b[1,3]==0)
set.seed(104729); a<-rrarefy(counts[1:2,],2)
set.seed(104729); check(identical(a,rrarefy(counts[1:2,],2)))
check(all(rowSums(a)==2))
check(all(ordinate_bray(matrix(0,3,3))==0))
check(identical(dim(ordinate_bray(matrix(c(0,1,1,0),2))),c(2L,2L)))
cat(n,'analysis assertions passed\n')
